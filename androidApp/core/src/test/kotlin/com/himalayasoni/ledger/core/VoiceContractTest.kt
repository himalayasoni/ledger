package com.himalayasoni.ledger.core

import com.google.gson.Gson
import com.himalayasoni.ledger.core.domain.Usual
import com.himalayasoni.ledger.core.model.EntryType
import com.himalayasoni.ledger.core.voice.ParsedLine
import com.himalayasoni.ledger.core.voice.VoiceContext
import com.himalayasoni.ledger.core.voice.parseLine
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test
import java.io.File
import java.time.LocalDate

/**
 * Contract test: every phrase in spec/voice-phrases.json must parse to exactly what the web
 * app's parseLine() returned for it (the file is generated by running the web code).
 */
class VoiceContractTest {
    @Suppress("UNCHECKED_CAST")
    private val spec: Map<String, Any?> by lazy {
        val file = listOf("../../spec/voice-phrases.json", "spec/voice-phrases.json").map(::File).first { it.exists() }
        Gson().fromJson(file.readText(), Map::class.java) as Map<String, Any?>
    }

    /** The app state the web parser was run with, as the Kotlin parser takes it. */
    @Suppress("UNCHECKED_CAST")
    private val context: VoiceContext by lazy {
        val c = spec["context"] as Map<String, Any?>
        val usuals = (c["templates"] as List<Map<String, String>>).map {
            val desc = it.getValue("desc").trim()
            Usual(desc.lowercase(), desc, 0.0, EntryType.fromKey(it.getValue("type"))!!, it["cat"] ?: "", "", emptyList(), true, "", 1, 0)
        }
        VoiceContext(
            people = c["people"] as List<String>, categories = c["categories"] as List<String>, usuals = usuals,
            today = LocalDate.parse(c["today"] as String), // phrases like "on monday" count back from this day
        )
    }

    /** The parsed line in the web's shape, so the two can be compared field by field. */
    private fun ParsedLine.asWeb(): Map<String, Any> = linkedMapOf(
        "type" to type.key, "amount" to amount, "person" to person, "with" to withPeople,
        "desc" to description, "cat" to category, "mode" to mode, "day" to daysAgo,
    )

    /** Gson reads every JSON number as a Double; make ours comparable. */
    private fun normalise(v: Any?): Any? = when (v) {
        is Number -> v.toDouble()
        is List<*> -> v.map(::normalise)
        else -> v
    }

    @Suppress("UNCHECKED_CAST")
    @Test fun `every phrase parses exactly as the web app parses it`() {
        val cases = spec["cases"] as List<Map<String, Any?>>
        assertTrue("expected at least 200 phrases", cases.size >= 200)
        val failures = mutableListOf<String>()
        for (case in cases) {
            val say = case["say"] as String
            val expect = case["expect"] as Map<String, Any?>
            val got = parseLine(say, context).asWeb()
            assertTrue("$say: the contract has fields the parser doesn't return", got.keys == expect.keys)
            for ((field, want) in expect) {
                val have = got[field]
                if (normalise(want) != normalise(have)) failures += "\"$say\" -> $field: web says $want, Kotlin says $have"
            }
        }
        if (failures.isNotEmpty()) fail("${failures.size} differences from the web parser:\n" + failures.joinToString("\n"))
    }
}
